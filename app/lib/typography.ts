const NBSP = "\u00A0";
const WORD_JOINER = "\u2060";

// Короткие слова, после которых нельзя переносить строку: любые из 1–2 букв
// (в, у, и, с, на, по, к, до, из...) и несколько трёхбуквенных предлогов и союзов.
const SHORT = "[а-яёa-z]{1,2}|для|без|под|над|при|про|или|что|как";

/**
 * Расставляет неразрывные пробелы в русском тексте:
 * - после коротких слов («в пятницу» не разрывается после «в»);
 * - перед тире и точкой-разделителем (строка не начинается с «—» или «·»);
 * - между числом и словом после него («250 г», «54 BYN», «1–3 день»);
 * - после «ул.»;
 * - внутри диапазонов без пробелов («1–3», «8:00–20:00», «пн–пт»): после короткого
 *   тире браузер иначе разрывает строку («на 1–» / «3 день»).
 * Весь видимый текст страницы пропускаем через эту функцию.
 */
export function nb(text: string): string {
  return text
    .replace(/ (?=[—–·])/g, NBSP)
    .replace(new RegExp(String.raw`(?<=^|[\s(«—–·])(${SHORT}) `, "giu"), `$1${NBSP}`)
    .replace(/(\d) (?=[а-яёa-z])/giu, `$1${NBSP}`)
    .replace(/(?<=^|\s)(ул\.) /giu, `$1${NBSP}`)
    .replace(/(?<=\S)–(?=\S)/g, `–${WORD_JOINER}`);
}
